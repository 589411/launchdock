export type ViewKey =
  | 'touchpoints' | 'health' | 'rfm' | 'insight'
  | 'repurchase' | 'basket' | 'value' | 'insight2'
  | 'recommend' | 'segcopy' | 'triggers' | 'insight3'
  | 'experiment' | 'holdout' | 'risks' | 'insight4'
  | 'report';

/** 學員可以填「我的 AI 算出來的數字」來核對 */
export interface CheckSpec {
  id: ExpectedKey;
  label: string;
  unit: 'count' | 'percent' | 'days' | 'pp';
  /** 核對失敗時的提示（不給答案，提醒去追問 AI 的算法） */
  hint: string;
}

/** 由資料算出、可供核對的標準答案 */
export type ExpectedKey =
  | 'memberShare'
  | 'anonymousCount'
  | 'returnCount'
  | 'onceOnly'
  | 'top20Share'
  | 'medianInterval'
  | 'repeatRate'
  | 'repeatRevenueShare'
  | 'topPairCount'
  | 'ruleAudience'
  | 'triggerUnique'
  | 'baselineRate'
  | 'selectionGap'
  | 'sampleSize';

export interface SegmentDef {
  id: string;
  day: 1 | 2 | 3 | 4;
  /** 該天內的第幾段（1 起算） */
  order: number;
  title: string;
  goal: string;
  /** 任務說明（學員要回答的問題） */
  task: string;
  /** 貼給自己 AI 工具的提示詞範本；{columns} 會換成欄位名稱（只有欄名，沒有資料） */
  tryPrompt: string;
  view: ViewKey;
  checks?: CheckSpec[];
  takeawayLabel: string;
}

