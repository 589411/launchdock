export function questionsForDay(day: 3 | 4): PollQuestion[] {
  return questions.filter((q) => q.day === day);
}

export function findQuestion(id: string): PollQuestion | undefined {
  if (id === warmupQuestion.id) return warmupQuestion;
  return questions.find((q) => q.id === id);
}
