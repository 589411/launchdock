export interface PollQuestion {
  /** 資料庫存的題號，同時是講義上印的編號（小寫） */
  id: string;
  /** 講義上印的編號，如 "Q3" */
  label: string;
  /** 3 = 8/12，4 = 8/14 */
  day: 3 | 4;
  text: string;
  /** 選項文字，順序即 choice_index */
  options: string[];
  /** 講義位置，講師用來對頁（詳細版，只給講師端） */
  where: string;
  /** 學員端投票畫面上方那一行——這一題掛在課程的哪一段。
   *  投票是「課程中間停下來的互動」，不是問卷；學員要一眼看到自己在哪一段。 */
  segment: string;
  /** 講師按「停下來討論」後，學員端顯示的討論題。沒有它學員只會看到冷冰冰的「討論中」。 */
  discuss: string;
  /** 這題為什麼重要（投影時顯示在題目下方，也是講師的提詞） */
  star?: string;
  /** Colab 要先跑出什麼，才問這題 */
  colab?: string;
  /** 分布出來後講師講的重點（可直接照唸） */
  script: string;
  /** 第 2 層備案：跨業態對照表 */
  fallback?: {
    headers: string[];
    rows: string[][];
  };
  /** 沒有表格時的備案文字 */
  fallbackNote?: string;
}

